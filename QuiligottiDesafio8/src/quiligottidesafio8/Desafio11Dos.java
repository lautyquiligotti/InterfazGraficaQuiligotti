    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String nombre = txtAgregar.getText().trim();
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribí el nombre de la tarea.");
            return;
        }
        agregarTarea(nombre);
        txtAgregar.setText("");
        txtAgregar.requestFocus();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnCompletadaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompletadaActionPerformed
        int idx = lstTareas.getSelectedIndex();
        if (idx == -1) {
            JOptionPane.showMessageDialog(this, "Seleccioná una tarea de la lista.");
            return;
        }
        Tarea t = datos.get(idx);
        t.completada = !t.completada;   // alternar estado
        refrescarFila(idx);
    }//GEN-LAST:event_btnCompletadaActionPerformed

