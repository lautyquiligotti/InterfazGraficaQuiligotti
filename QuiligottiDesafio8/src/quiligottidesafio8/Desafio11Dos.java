    private void agregarTarea(String nombre) {
        Tarea t = new Tarea(nombre);
        datos.add(t);
        vistaModel.addElement("• " + nombre); // • pendiente, ✓ completada
    }

    private void refrescarFila(int i) {
        Tarea t = datos.get(i);
        String pref = t.completada ? "✓ " : "• ";
        vistaModel.set(i, pref + t.nombre);
    }

